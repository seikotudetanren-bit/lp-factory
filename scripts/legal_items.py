# 全角のかっこ・数字・ピリオドだけ半角にする（①②・イロハは ref に残すので触らない。NFKC は使わない）
_FW = str.maketrans("（）．。０１２３４５６７８９", "().." + "0123456789")


def _clean(s: str) -> str:
    return re.sub(r"\s+", "", (s or "").translate(_FW))


def normalize(raw: str) -> tuple[str | None, str]:
    """(正規コード または None, ref に回す残り) を返す。"""
    s = _clean(raw)
    if not s:
        return None, ""
    if s in CANONICAL:
        return s, ""
    if s in ALIASES:
        return ALIASES[s], ""
    # 指針の番号: 「Ⅵ4(1)」「Ⅵ.4（1）」「指針Ⅲ.3(2)②イ」などを拾う
    m = re.search(rf"([{_ROMAN}])\.?(\d)(?:\((\d)\))?(.*)$", s)
    if m:
        base = f"{m.group(1)}.{m.group(2)}" + (f"({m.group(3)})" if m.group(3) else "")
        rest = m.group(4)
        if base in CANONICAL:
            return base, rest
    for alias, code in ALIASES.items():
        if s.startswith(alias):
            return code, s[len(alias):]
    for code in CANONICAL:
        if not code.startswith(tuple(_ROMAN)) and s.startswith(code):
            return code, s[len(code):]
    return None, s


def describe() -> str:
    return "\n".join(f"  {k}: {v}" for k, v in CANONICAL.items())
